import AppKit
import XCTest
@testable import BigBangSelection

final class SystemClipboardTests: XCTestCase {
    @MainActor func testEditorMetadataGraceFollowsFocusedInputNotApplication() {
        for marker in ["inputarea", "native-edit-context", "ime-text-area"] {
            XCTAssertTrue(SystemSelectionEnvironment.isEditorInput(classes: [marker, "monaco-mouse-cursor-text"]))
        }
        for classes in [["xterm-helper-textarea"], ["input"], ["monaco-inputbox"], ["monaco-editor"], []] {
            XCTAssertFalse(SystemSelectionEnvironment.isEditorInput(classes: classes))
        }
    }
    @MainActor func testPrivatePasteboardMarkerAndMultipleFormatsRoundTrip() throws {
        // A named test pasteboard exercises AppKit without touching the user's general clipboard.
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        let first = NSPasteboardItem()
        first.setString("原剪贴板", forType: .string)
        first.setData(Data([1, 2, 3, 4]), forType: .rtf)
        let second = NSPasteboardItem()
        second.setData(Data([5, 6, 7]), forType: .init("app.mayfiles.BigBang.test-format"))
        XCTAssertTrue(board.writeObjects([first, second]))
        let environment = SystemSelectionEnvironment(pasteboard: board)
        let original = environment.clipboardSnapshot()
        XCTAssertEqual(original.count, 2)
        environment.installMarker("test-marker")
        XCTAssertNil(board.string(forType: .string))
        XCTAssertEqual(board.string(forType: .init("app.mayfiles.BigBang.selection-probe")), "test-marker")
        environment.restoreClipboard(original)
        XCTAssertEqual(environment.clipboardSnapshot(), original)
    }

    @MainActor func testEditorNativeMetadataReachesSelectionParser() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        board.clearContents()
        board.setString("Entire current line\n", forType: .string)
        board.setData(Data(#"{"version":1,"isFromEmptySelection":true}"#.utf8), forType: .init("vscode-editor-data"))
        let environment = SystemSelectionEnvironment(pasteboard: board)
        let clipboard = environment.clipboard
        XCTAssertTrue(clipboard.isStable)
        XCTAssertEqual(clipboard.text, "Entire current line\n")
        XCTAssertEqual(EditorClipboardMetadata.isFromEmptySelection(clipboard.customData), true)
    }

    @MainActor func testChromiumNativePasteboardTypeReachesSelectionParser() throws {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        // Fixed external-format fixture: Chromium Pickle with one vscode-editor-data
        // entry, {"version":1,"isFromEmptySelection":false}; not generated by the decoder.
        let data = try XCTUnwrap(Data(base64Encoded: "hAAAAAEAAAASAAAAdgBzAGMAbwBkAGUALQBlAGQAaQB0AG8AcgAtAGQAYQB0AGEAKgAAAHsAIgB2AGUAcgBzAGkAbwBuACIAOgAxACwAIgBpAHMARgByAG8AbQBFAG0AcAB0AHkAUwBlAGwAZQBjAHQAaQBvAG4AIgA6AGYAYQBsAHMAZQB9AA=="))
        board.clearContents()
        XCTAssertTrue(board.setString("真正的选区\n", forType: .string))
        XCTAssertTrue(board.setData(data, forType: .init("org.chromium.web-custom-data")))
        let clipboard = SystemSelectionEnvironment(pasteboard: board).clipboard
        XCTAssertEqual(clipboard.customData["org.chromium.web-custom-data"], data)
        XCTAssertEqual(EditorClipboardMetadata.isFromEmptySelection(clipboard.customData), false)
    }

    @MainActor func testCopyPasteControllerNativeTypeReachesSelectionParser() {
        let board = NSPasteboard.withUniqueName()
        defer { board.releaseGlobally() }
        board.clearContents()
        XCTAssertTrue(board.setString("selected editor text", forType: .string))
        XCTAssertTrue(board.setData(Data(#"{"defaultPastePayload":{"pasteOnNewLine":false}}"#.utf8),
                                   forType: .init("application/vnd.code.copymetadata")))
        let clipboard = SystemSelectionEnvironment(pasteboard: board).clipboard
        XCTAssertEqual(EditorClipboardMetadata.inspect(clipboard.customData), .selection)
    }
}
